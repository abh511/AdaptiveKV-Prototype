"""
benchmarks/make_report.py
-------------------------
Builds results/VERIFICATION.md from generated outputs only:

  results/pytest_report.xml            every test case and its real outcome
  results/DECISION_REPORT_<model>.md   two-tier vs INT2, adaptive vs recency (quality)
  results/PASSKEY_REPORT_<model>.md    retrieval through each cache
  results/IMPORTANCE_REPORT_<model>.md does importance predict future attention?
  results/summary.csv                  memory / effective bits / speed (benchmark)
  results/extrapolated.csv             EXTRAPOLATED, kept in a separate section

Nothing is typed in by hand; a missing input is reported as missing.
Produce the test record first:
  python -m pytest tests -q --junitxml=results/pytest_report.xml
Then:
  python benchmarks/make_report.py
"""

import csv
import datetime
import glob
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "results")
OUT = os.path.join(RES, "VERIFICATION.md")


def sections(md: str) -> dict:
    """'## Title' -> body text (until the next '## ')."""
    parts = re.split(r"^## ", md, flags=re.M)
    return {p.split("\n", 1)[0].strip(): p.split("\n", 1)[1] if "\n" in p else "" for p in parts[1:]}


def pick(md_path: str, wanted: list) -> list:
    if not os.path.exists(md_path):
        return [f"_missing: {os.path.relpath(md_path, ROOT)}_\n"]
    secs = sections(open(md_path, encoding="utf-8").read())
    out = []
    for w in wanted:
        key = next((k for k in secs if k.startswith(w)), None)
        if key:
            out.append(f"#### {key}\n\n{secs[key].strip()}\n")
    return out


def tests_section() -> list:
    path = os.path.join(RES, "pytest_report.xml")
    if not os.path.exists(path):
        return ["_missing: results/pytest_report.xml (run pytest with --junitxml, see header)_\n"]
    root = ET.parse(path).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    stamp = suite.get("timestamp", "?")
    rows, counts = [], {"passed": 0, "failed": 0, "error": 0, "skipped": 0}
    for tc in suite.iter("testcase"):
        if tc.find("failure") is not None:
            st = "failed"
        elif tc.find("error") is not None:
            st = "error"
        elif tc.find("skipped") is not None:
            st = "skipped"
        else:
            st = "passed"
        counts[st] += 1
        rows.append((tc.get("classname", "").replace("tests.", ""), tc.get("name"), st, float(tc.get("time", 0))))
    out = [f"Run at {stamp}: **{counts['passed']} passed, {counts['failed']} failed, "
           f"{counts['error']} errors, {counts['skipped']} skipped** ({len(rows)} test cases).\n",
           "| File | Test case | Result | Time (s) |", "|---|---|---|---|"]
    out += [f"| {c} | `{n}` | {s} | {t:.2f} |" for c, n, s, t in rows]
    return out + [""]


def csv_table(path: str, cols: list, fmt: dict) -> list:
    if not os.path.exists(path):
        return [f"_missing: {os.path.relpath(path, ROOT)}_\n"]
    rows = list(csv.DictReader(open(path)))
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c, "")
            try:
                cells.append(fmt[c](float(v)) if c in fmt and v not in ("", "None") else (v or "n/a"))
            except ValueError:
                cells.append(v)
        out.append("| " + " | ".join(cells) + " |")
    return out + [""]


def main():
    tags = sorted({re.sub(r"^DECISION_REPORT_|\.md$", "", os.path.basename(p))
                   for p in glob.glob(os.path.join(RES, "DECISION_REPORT_*.md"))} |
                  {re.sub(r"^PASSKEY_REPORT_|\.md$", "", os.path.basename(p))
                   for p in glob.glob(os.path.join(RES, "PASSKEY_REPORT_*.md"))})
    L = []
    w = L.append
    w("# AdaptiveKV verification record\n")
    w(f"Generated by `benchmarks/make_report.py` on {datetime.datetime.now().isoformat(timespec='seconds')} "
      "from files in `results/` only. Every number was measured on this machine by the scripts named in "
      "each section. Do not edit by hand; regenerate.\n")
    w("## 1. Test suite\n")
    L += tests_section()

    for tag in tags:
        w(f"## 2. Quality and design decisions: {tag}\n")
        w("Source: `decision_test.py` (teacher-forced perplexity, KL and top-1 vs FP16 through each KV cache).\n")
        L += pick(os.path.join(RES, f"DECISION_REPORT_{tag}.md"),
                  ["Setup", "Results", "Decision 1", "Question 2:", "Question 2b"])
        w(f"### Passkey retrieval: {tag}\n")
        w("Source: `passkey.py`.\n")
        L += pick(os.path.join(RES, f"PASSKEY_REPORT_{tag}.md"),
                  ["Overall accuracy", "Accuracy by context", "Adaptive vs recency"])
        w(f"### Does importance predict future attention? {tag}\n")
        w("Source: `importance_analysis.py`.\n")
        L += pick(os.path.join(RES, f"IMPORTANCE_REPORT_{tag}.md"), ["Result", "How to read"])

    w("## 3. Memory, effective bits and speed (measured)\n")
    w("Source: `benchmarks/run_baselines.py` then `benchmarks/summarise.py`. Bytes are real tensor `.nbytes`; "
      "mean over windows.\n")
    kb = lambda v: f"{v / 1024:,.0f}"
    f2 = lambda v: f"{v:.2f}"
    L += csv_table(os.path.join(RES, "summary.csv"),
                   ["method", "context_length", "n_runs", "n_oom", "n_error", "kv_bytes_real_mean",
                    "compression_ratio_mean", "effective_bits_mean", "prefill_s_mean",
                    "decode_ms_per_tok_mean", "peak_vram_bytes_mean"],
                   {"kv_bytes_real_mean": kb, "compression_ratio_mean": f2, "effective_bits_mean": f2,
                    "prefill_s_mean": lambda v: f"{v:.3f}", "decode_ms_per_tok_mean": lambda v: f"{v:.1f}",
                    "peak_vram_bytes_mean": lambda v: f"{v / 1024 ** 3:.2f} GB"})
    w("`kv_bytes_real_mean` in KB. Peak VRAM is NOT reduced by this design: the cache is dequantized to "
      "FP16 for each attention call.\n")

    w("## 4. EXTRAPOLATED (not measured)\n")
    w("Source: `benchmarks/extrapolate.py`: measured stored/FP16 byte ratio x FP16 KV size from each model's "
      "config.json. Assumes the ratio carries over; unverified for adaptive/recency.\n")
    L += csv_table(os.path.join(RES, "extrapolated.csv"),
                   ["LABEL", "model", "method", "context_length", "measured_ratio", "kv_MB_extrap", "fp16_MB_extrap"],
                   {"measured_ratio": lambda v: f"{v:.4f}", "kv_MB_extrap": lambda v: f"{v:.1f}",
                    "fp16_MB_extrap": lambda v: f"{v:.1f}"})

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
