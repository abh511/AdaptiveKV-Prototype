"""
benchmarks/make_paper_report.py
-------------------------------
Draft research-paper report, generated from results/ only:
  results/PAPER_REPORT.md  (+ results/figures/*.png|pdf from make_figures.py)

Every number in the text is computed here from the result files; statements
are phrased from the data (e.g. "significant" only when the paired test says
so). Nothing is typed in by hand. Run after the experiments:
  python benchmarks/make_figures.py && python benchmarks/make_paper_report.py
"""

import csv
import datetime
import math
import os
import re
import sys

import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "results")
OUT = os.path.join(RES, "PAPER_REPORT.md")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_report import sections, tests_section  # noqa: E402


def rd(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def exists(name):
    return os.path.exists(os.path.join(RES, name))


def fig(name, caption, L):
    if exists(f"figures/{name}.png"):
        L.append(f"![{caption}](figures/{name}.png)\n")
        L.append(f"*{caption}* (vector version: `results/figures/{name}.pdf`)\n")


def report_section(path, title_prefix):
    if not os.path.exists(path):
        return None
    secs = sections(open(path, encoding="utf-8").read())
    key = next((k for k in secs if k.startswith(title_prefix)), None)
    return secs[key].strip() if key else None


def md_rows(table_text):
    """Rows (list of cells) of the first markdown table in text."""
    rows = []
    for line in table_text.splitlines():
        if line.startswith("|") and not line.startswith("|---"):
            rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows[1:] if rows else []


def main():
    cfg = yaml.safe_load(open(os.path.join(ROOT, "config.yaml")))
    tags = sorted(re.sub(r"^decision_|_summary\.csv$", "", p) for p in os.listdir(RES)
                  if p.startswith("decision_") and p.endswith("_summary.csv"))
    main_tag = cfg["model_id"].split("/")[-1]
    S = {t: {r["variant"]: r for r in rd(os.path.join(RES, f"decision_{t}_summary.csv"))
             if f(r.get("n_windows")) > 0} for t in tags}
    L = []
    w = L.append

    # ---- key numbers ---------------------------------------------------------
    m = S.get(main_tag, {})
    def g(v, k, t=main_tag):
        return f(S.get(t, {}).get(v, {}).get(k))
    i4n, i4o = g("int4_uniform", "kl"), g("int4_uniform [per-token keys]", "kl")
    i2n, i2o = g("int2_uniform", "kl"), g("int2_uniform [per-token keys]", "kl")
    rep_main = os.path.join(RES, f"DECISION_REPORT_{main_tag}.md")
    bm = report_section(rep_main, "Question 2b")
    bm_rows = md_rows(bm) if bm and "No pair" not in bm else []
    n_bm = len(bm_rows)
    n_bm_a = sum(1 for r in bm_rows if r[-1].startswith("adaptive better"))
    n_bm_r = sum(1 for r in bm_rows if r[-1].startswith("recency better"))
    d1 = report_section(rep_main, "Decision 1") or ""
    d1_result = re.search(r"\*\*Result:(.*?)\*\*", d1, re.S)

    # ---- title / abstract ----------------------------------------------------
    w("# AdaptiveKV: Attention-Guided Mixed-Precision KV-Cache Quantization on a 4 GB GPU\n")
    w(f"*Draft generated by `benchmarks/make_paper_report.py` on "
      f"{datetime.datetime.now().isoformat(timespec='minutes')} from `results/`. All numbers are measured "
      "on this machine (NVIDIA RTX 3050 Laptop, 4 GB); extrapolations are labelled. Regenerate, do not edit.*\n")
    w("## Abstract\n")
    abs_parts = []
    abs_parts.append(
        "The key-value (KV) cache of autoregressive LLMs grows linearly with context and dominates memory "
        "traffic during decoding. AdaptiveKV stores each cached token at INT8, INT4 or INT2, chosen by an "
        "exponential moving average (EMA) of the attention it receives, under fixed tier quotas, in pure "
        "PyTorch on a consumer GPU.")
    if not math.isnan(i4o) and not math.isnan(i4n):
        abs_parts.append(
            f"We find that the quantization granularity of keys decides whether low precision works at all: "
            f"quantizing keys per channel (KIVI-style) instead of per token lowers the KL divergence to FP16 "
            f"of uniform INT4 from {i4o:.3g} to {i4n:.3g} nats/token on {main_tag}"
            + (f", and of uniform INT2 from {i2o:.3g} to {i2n:.3g}" if not math.isnan(i2o) else "") + ".")
    for t in tags:
        if t == main_tag:
            continue
        a, b = g("int4_uniform [per-token keys]", "kl", t), g("int4_uniform", "kl", t)
        if not (math.isnan(a) or math.isnan(b)):
            abs_parts.append(
                f"On {t} the per-token scheme makes uniform INT4 collapse (KL {a:.3g}, perplexity "
                f"{g('int4_uniform [per-token keys]', 'ppl_delta_pct', t):+,.0f}%), while per-channel keys give "
                f"KL {b:.3g} ({g('int4_uniform', 'ppl_delta_pct', t):+.1f}% perplexity).")

    def pval(cell):
        mm = re.search(r"p=([0-9.eE+-]+)", cell)
        return float(mm.group(1)) if mm else float("nan")

    def sig(cell):
        mm = re.search(r"^([+-][0-9.]+) \[([+-][0-9.]+), ([+-][0-9.]+)\]", cell)
        return bool(mm) and (float(mm.group(2)) > 0 or float(mm.group(3)) < 0) and pval(cell) < 0.05

    for r in bm_rows:
        a_lab, r_lab, bits, d_nll, d_kl, d_top = r[:6]
        kl_word = "significantly lower" if sig(d_kl) and d_kl.startswith("-") else (
            "significantly higher" if sig(d_kl) else "not significantly different")
        top_word = ("significantly higher" if sig(d_top) and d_top.startswith("+") else
                    "significantly lower" if sig(d_top) else "not significantly different")
        nll_word = ("significantly lower" if sig(d_nll) and d_nll.startswith("-") else
                    "significantly higher" if sig(d_nll) else "not significantly different")
        abs_parts.append(
            f"At matched memory ({bits} bits), attention-guided allocation ({a_lab}) had {kl_word} KL to FP16 "
            f"than the recency heuristic ({r_lab}; p={pval(d_kl):.2g}), {top_word} top-1 agreement "
            f"(p={pval(d_top):.2g}) and {nll_word} perplexity (p={pval(d_nll):.2g}).")
    if not math.isnan(g("int4_uniform", "eff_bits")):
        abs_parts.append(
            f"Uniform INT4 with per-channel keys stores {g('int4_uniform', 'eff_bits'):.2f} effective bits per "
            f"value ({g('int4_uniform', 'compression_x'):.2f}x smaller than FP16, all overheads included) at "
            f"{g('int4_uniform', 'ppl_delta_pct'):+.1f}% perplexity.")
    if d1_result and "no three-tier" in d1_result.group(1):
        abs_parts.append("However, under our pre-registered Pareto rule no three-tier (INT2) mix beat uniform "
                         "INT4 at equal or fewer bits: with per-channel keys, uniform INT4 is already near-lossless, "
                         "so the measured benefit of attention guidance is in the mixed-precision regime, not "
                         "in beating the best uniform format.")
    elif d1_result:
        abs_parts.append(f"Three-tier rule result: {d1_result.group(1).strip()}")
    abs_parts.append("Peak GPU memory is not reduced by this software prototype (the cache is dequantized for "
                     "each attention call); the savings are in stored bytes.")
    w(" ".join(abs_parts) + "\n")

    # ---- method --------------------------------------------------------------
    w("## 1. Method\n")
    w("1. **Importance.** During each forward pass a hook on every attention module reduces the attention "
      "matrix to one score per cached token (mean over heads of the last "
      f"{cfg.get('importance_window')} query row(s), uniform over layers) and discards the matrix. "
      f"Scores are smoothed with an EMA (alpha = {cfg['ema_alpha']}); a new token starts at its raw score.")
    w(f"2. **Tiers and quotas.** Fractions p8/p4/p2 of the cache are held at INT8/INT4/INT2. The first "
      f"{cfg.get('sink_tokens')} tokens (attention sinks) are pinned at INT8. The newest "
      f"{cfg.get('recent_tokens')} tokens stay FP16. When a token leaves that window it gets a tier; tiers are "
      "re-evaluated every step and may only be **demoted**, capped by the quotas, least-important first.")
    w(f"3. **Storage.** Values are quantized per token (asymmetric, groups of {cfg['quant_group_size']}). "
      f"Keys are quantized **per channel**: the keys of the same tier inside a block of "
      f"{cfg.get('key_group_tokens', 32)} positions share one scale and zero-point per (head, channel). A key "
      "waits at FP16 until its block is complete. INT4/INT2 codes are bit-packed (2/4 per byte).")
    w("4. **Accounting.** Memory is the sum of `.nbytes` of every stored tensor: codes, scales, zero-points, "
      "FP16 window, pending keys and the 1-byte tier index. Effective bits = bytes x 8 / number of FP16 values.")
    w("5. **Baselines.** FP16 (native cache), uniform INT8/INT4/INT2 (same quantizer), and a recency heuristic "
      "that gives the newest tokens the highest precision at the same fractions and the same sink pins.\n")

    # ---- setup -----------------------------------------------------------------
    w("## 2. Experimental setup\n")
    setup = report_section(rep_main, "Setup")
    if setup:
        w(setup + "\n")
    w("**Metrics.** Perplexity under teacher forcing *through* each KV cache; KL(FP16 ‖ method) of the "
      "next-token distribution and top-1 agreement with FP16 given the identical prefix; effective bits and "
      "compression from real tensor sizes; passkey retrieval accuracy (Wilson 95% CI); paired adaptive-vs-"
      "recency tests over identical windows (bootstrap 95% CI and Wilcoxon signed-rank; McNemar for passkey).\n")

    # ---- results ---------------------------------------------------------------
    w("## 3. Results\n")
    w("### 3.1 Key quantization granularity decides whether low precision works\n")
    fig("fig2_key_scheme_ablation", "Figure 1. KL to FP16 with per-token vs per-channel key quantization.", L)
    w("| Model | Variant | KL per-token keys | KL per-channel keys | Ratio |\n|---|---|---|---|---|")
    for t in tags:
        for new, old in (("int4_uniform", "int4_uniform [per-token keys]"), ("int2_uniform", "int2_uniform [per-token keys]"),
                         ("adaptive 8/4 0.50/0.50", "adaptive 8/4 0.50/0.50 [per-token keys]")):
            if new in S[t] and old in S[t]:
                a, b = f(S[t][old]["kl"]), f(S[t][new]["kl"])
                w(f"| {t} | {new} | {a:.4g} | {b:.4g} | {a / b:.0f}x |")
    w("")
    if d1_result:
        w(f"**Three tiers (INT2).** Pre-registered rule result: {d1_result.group(1).strip()}\n")

    for k, t in enumerate(sorted(tags, key=lambda x: x != main_tag)):
        w(f"### 3.2{'abcdefgh'[k]} Quality-memory trade-off: {t}\n")
        fig(f"fig1_pareto_kl_{t}", f"Figure 2. Effective bits vs KL to FP16 ({t}).", L)
        res = report_section(os.path.join(RES, f"DECISION_REPORT_{t}.md"), "Results")
        if res:
            w(res + "\n")

    w("### 3.3 Attention-guided vs recency at matched memory\n")
    fig(f"fig3_bitmatched_{main_tag}", "Figure 3. Per-window KL at matched memory.", L)
    for t in tags:
        sec = report_section(os.path.join(RES, f"DECISION_REPORT_{t}.md"), "Question 2b")
        if sec:
            w(f"**{t}**\n\n{sec}\n")

    if exists(f"PASSKEY_REPORT_{main_tag}.md"):
        w("### 3.4 Long-context retrieval (passkey)\n")
        fig(f"fig5_passkey_{main_tag}", "Figure 4. Passkey retrieval accuracy.", L)
        for title in ("Overall accuracy", "Adaptive vs recency"):
            sec = report_section(os.path.join(RES, f"PASSKEY_REPORT_{main_tag}.md"), title)
            if sec:
                w(f"**{title}**\n\n{sec}\n")

    if exists(f"IMPORTANCE_REPORT_{main_tag}.md"):
        w("### 3.5 Why: does attention importance predict future attention?\n")
        fig(f"fig6_importance_recall_{main_tag}", "Figure 5. Share of future attention kept at INT8.", L)
        sec = report_section(os.path.join(RES, f"IMPORTANCE_REPORT_{main_tag}.md"), "Result")
        if sec:
            w(sec + "\n")

    if exists("summary.csv"):
        w("### 3.6 Stored memory and speed across context lengths\n")
        fig("fig4_kv_memory_vs_context", "Figure 6. Stored KV bytes vs context length.", L)
        w("| Method | Context | Stored KV (MiB) | Compression | Eff. bits | Prefill (s) | Decode (ms/token) | Peak VRAM (GB) |")
        w("|---|---|---|---|---|---|---|---|")
        for r in rd(os.path.join(RES, "summary.csv")):
            w(f"| {r['method']} | {r['context_length']} | {f(r['kv_bytes_real_mean']) / 2**20:.2f} | "
              f"{f(r['compression_ratio_mean']):.2f}x | {f(r['effective_bits_mean']):.2f} | "
              f"{f(r.get('prefill_s_mean')):.3f} | {f(r.get('decode_ms_per_tok_mean')):.1f} | "
              f"{f(r['peak_vram_bytes_mean']) / 1024**3:.2f} |")
        w("\nDecode is slower than FP16: the prototype dequantizes the whole cache in Python/PyTorch every "
          "step; fused dequantize-attention kernels would be needed for a speed-up.\n")

    if exists("extrapolated.csv"):
        w("### 3.7 EXTRAPOLATED: larger contexts and models (not measured)\n")
        w("Measured stored/FP16 byte ratio x FP16 KV size from each model's config.json. Assumes the ratio "
          "carries over; unverified for adaptive/recency.\n")
        w("| Model | Method | Context | KV MiB (extrap.) | FP16 MiB |\n|---|---|---|---|---|")
        for r in rd(os.path.join(RES, "extrapolated.csv")):
            if r["context_length"] in ("8192", "32768"):
                w(f"| {r['model'].split('/')[-1]} | {r['method']} | {r['context_length']} | "
                  f"{f(r['kv_MB_extrap']):.1f} | {f(r['fp16_MB_extrap']):.1f} |")
        w("")

    # ---- limitations / reproducibility -------------------------------------
    w("## 4. Limitations\n")
    w("- Peak VRAM is not reduced (dequantize-then-attend); only stored bytes shrink.")
    w("- Decode latency is higher than FP16 in this pure-PyTorch prototype.")
    w("- Quality is measured on WikiText-2 and a synthetic passkey task; no downstream benchmarks.")
    w("- With per-channel keys, scattering tiers across key blocks stores more scale sets, so adaptive uses "
      "more bits than recency at equal fractions; equal-memory comparisons (Section 3.3) account for this.")
    if len(tags) > 1:
        w("- Larger-model results use few windows (time budget) and CPU-offloaded weights; treat them as a "
          "confirmation, not a precise estimate.")
    w("")
    w("## 5. Reproducibility\n")
    w("```\npython -m pytest tests -q --junitxml=results/pytest_report.xml\npython passkey.py\n"
      "python importance_analysis.py\npython decision_test.py\n"
      "python benchmarks/run_baselines.py --config config_bench.yaml && python benchmarks/summarise.py\n"
      "python benchmarks/extrapolate.py\npython benchmarks/make_figures.py && python benchmarks/make_paper_report.py\n```\n")
    w("### Test suite\n")
    L.extend(tests_section()[:1])
    w("\nFull per-test listing: `results/VERIFICATION.md`.\n")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
